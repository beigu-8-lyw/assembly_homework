/* ============================================================
 * 作业3：用 C 语言求 1+2+...+100，并输出结果 5050
 *
 * 编译（MinGW GCC）：gcc -O0 sum.c -o sum_c.exe
 * 编译（Turbo C）  ：tcc sum.c
 * ============================================================ */
#include <stdio.h>

int main(void)
{
    int i;                  /* 循环变量 */
    int sum = 0;            /* 累加和，16 位 int 足以表示 5050 */

    for (i = 1; i <= 100; i++)
        sum += i;

    printf("%d\n", sum);    /* 输出 5050 */

    return 0;
}
